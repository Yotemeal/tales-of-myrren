'use strict';
// Deterministic XP/hour benchmark of currently available content. This models
// sustained stationary gathering, not travel, respawn waits, depleted nodes,
// inventory trips, food/bait costs or other live-play interruptions.
const assert=require('node:assert/strict');
const createGame=require('./game-runtime.cjs');

(async()=>{
  const {game:g}=await createGame();
  // Keep the historical XP curve and serialized experience untouched.
  for(const [level,expected] of [[1,0],[10,1154],[30,14353],[70,3253985],[85,29454989]])
    assert.equal(g.xpTable[level],expected,'save-compatible XP threshold at level '+level);

  const skills=['woodcutting','mining','fishing'];
  const bestToolMat=(skill,level)=>{
    const kinds=skill==='woodcutting'?['axe']:skill==='mining'?['pick']:['net','rod'];
    return Math.max(1,...Object.values(g.DEFS).filter(d=>kinds.includes(d.kind)&&d.req<=level).map(d=>d.mat));
  };
  const chance=(n,level,toolMat)=>Math.max(.05,Math.min(.92,n.base+(level-n.req)*.025+Math.max(0,toolMat-2)*.06));
  const rate=(n,level,mat)=>n.xp*chance(n,level,mat)*3600/(n.skill==='fishing'?3.3:1.8);
  const best=(skill,level)=>{
    const mat=bestToolMat(skill,level);
    return Object.entries(g.NT).filter(([,n])=>n.skill===skill&&level>=n.req)
      .map(([key,n])=>({key,xph:rate(n,level,mat)}))
      .sort((a,b)=>b.xph-a.xph)[0];
  };
  const bands=[1,10,20,30,40,55,60,70,85,95];
  const previous=Object.fromEntries(skills.map(skill=>[skill,0]));
  for(const level of bands){
    const row=skills.map(skill=>({skill,...best(skill,level)}));
    for(const r of row){
      assert(Number.isFinite(r.xph)&&r.xph>0,r.skill+' has no usable gathering XP at level '+level);
      assert(r.xph>=previous[r.skill],r.skill+' unexpectedly gets slower after leveling to '+level);
      previous[r.skill]=r.xph;
    }
    const values=row.map(r=>r.xph),ratio=Math.max(...values)/Math.min(...values);
    assert(ratio<=2.2,
      'Gathering XP diverges at level '+level+': '+row.map(r=>r.skill+' '+Math.round(r.xph)+'/hr').join('; '));
  }

  // Rare high-level drops remain rare: balance their XP reward without
  // inflating ore, wood or fish success rates and the in-game economy.
  assert.equal(g.NT.aether.base,.1);
  assert.equal(g.NT.meteorite.base,.08);
  assert.equal(g.NT.myrren.base,.1);
  assert.equal(g.NT.spot5.base,.1);
  assert.deepEqual(
    ['tree','oak','maple','elder','myrren'].map(k=>g.NT[k].xp),
    [25,55,120,520,1900],'forestry tier reward progression');
  assert.deepEqual(
    ['copper','iron','coal','cobalt','obsidianite','aether','meteorite'].map(k=>g.NT[k].xp),
    [18,45,75,190,300,650,900],'delving tier reward progression');
  assert.deepEqual(
    ['spot1','spot2','spot3','spot4','spot5'].map(k=>g.NT[k].xp),
    [28,68,150,400,1550],'fishing tier reward progression');

  // Cooking consumes the fish generated by Fishing. Success chance at the
  // unlock level is 50%, so compare success-adjusted XP per one raw catch.
  for(const [raw,r] of Object.entries(g.COOK)){
    const caught=Object.values(g.NT).find(n=>n.item===raw);
    assert(caught,'no fishing source for '+raw);
    const expectedXpPerRaw=r.xp*.7; // 70% cook success five levels after unlock
    assert(expectedXpPerRaw>=caught.xp*.55&&expectedXpPerRaw<=caught.xp*1.3,
      raw+' cooking XP is wildly out of line with the effort to catch it');
  }

  // The XP split changes: smelting now accounts for ~40% rather than ~33%
  // of the XP from turning ore into equipment, with the TOTAL reward within
  // six percent of the old material-to-gear chain.
  const old=[12,30,55,140,300,600,1000];
  for(let i=0;i<g.SMELT.length;i++){
    const recipe=g.SMELT[i],kind='sword',bars=g.FORGE[kind],xpForGear=Math.round(bars*recipe.xp*1.5);
    const chainXp=bars*recipe.xp+xpForGear,oldChainXp=bars*old[i]*3;
    assert(Math.abs(chainXp-oldChainXp)/oldChainXp<=.06,recipe.id+' alters ore-to-gear XP too much');
    assert(recipe.xp>0&&Number.isInteger(xpForGear));
    assert(Math.abs((bars*recipe.xp)/chainXp-.4)<.02,'smelting share of XP should be about forty percent');
  }

  assert.deepEqual(
    Object.fromEntries(Object.entries(g.MT).map(([name,m])=>[name,g.combatKillXp(m)])),
    {slime:5,goblin:12,wolf:44,boar:22,bear:168,cave:1050,abear:3120},
    'normal mob XP is stable and elite kills cannot leapfrog entire level brackets');
  assert(g.combatKillXp(g.MT.cave)>g.combatKillXp(g.MT.bear));
  assert(g.combatKillXp(g.MT.abear)>g.combatKillXp(g.MT.cave));

  // Visual XP drops still display the actual awarded amount.
  const before=g.save.xp.forging;
  g.addXp('forging',g.SMELT[0].xp);
  assert.equal(g.save.xp.forging-before,g.SMELT[0].xp);
  assert.equal(g.xpPopups[0].amount,g.SMELT[0].xp);
  console.log('PASS: save-compatible curve, gathering XP/hour parity at 10 milestones, cooking input economy, smithing chain split, elite XP and popup amounts');
})().catch(err=>{console.error(err);process.exitCode=1});
