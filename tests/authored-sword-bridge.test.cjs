const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const window={};
vm.runInNewContext(fs.readFileSync('public/authored-sword-bridge.js','utf8'),{window,Error,Number});
const create=window.MyrrenAuthoredSwordBridge.create;
const calls=[];
const swords={ready:true,draw:(...args)=>{calls.push(args);return true}};
const motion={angle:age=>age<0?-.35:age/320};
const paint=create(swords,motion);
const ctx={};
assert.equal(paint(ctx,{x:12,y:20,material:6,direction:'left',pose:'attack',age:160}),true);
assert.equal(calls.length,1);
assert.equal(calls[0][0],ctx);
assert.deepEqual(calls[0].slice(1,5),[6,12,20,-1]);
assert.equal(calls[0][5],.5);
assert.equal(paint(ctx,{x:14,y:22,material:6,direction:'front',pose:'idle',age:400}),true);
assert.equal(calls[1][4],1);
assert.equal(calls[1][5],-.35);
swords.ready=false;
assert.equal(paint(ctx,{x:0,y:0,material:6,direction:'right',pose:'attack',age:0}),false);
assert.equal(calls.length,2,'unloaded sword must not draw');
assert.throws(()=>paint(ctx,{x:NaN,y:0,material:6}),/socket/);
assert.throws(()=>create(null,motion),/required/);
console.log('PASS: authored glove socket drives real sword draw, facing and attack angle');
